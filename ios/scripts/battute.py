#!/usr/bin/env python3
"""NASTY catalogs (T-024, D-046): generates the on-board catalogs and the files for the site from the approved ones.

Sources: ios/docs/design/T-021-nasty/catalogo/catalogo-approvato.json   Italian (id, livello, situazione, testo)
         ios/docs/design/T-021-nasty/catalogo/lingue/<lingua>.json        the other languages, same ids (T-025)
         ios/docs/design/T-021-nasty/catalogo/vincoli.json                       `ore` and `evento` by id
Outputs: ios/Sources/StepTellerCore/NastyCatalog+Bordo.swift       (the same JSON, inside the app)
         neat/nasty/<lingua>/battute.json                            (published on the site with the merge on main)

What the script adds to the approved lines, without changing a word of them:
  - `titolo`: the notification lines are written «Titolo / testo»: the part before « / » becomes the title;
  - `ore`: the hours a line can be said in, when its text names them («Sono le 11», «Mezzogiorno», «Fine giornata»);
  - `evento`: the event a line talks about, when it only makes sense with it («Obiettivo abbassato», «Jolly usato»,
    «Record»). Both come from vincoli.json, written by hand by id and the same in every language: a new approved line
    that names an hour or an event must be added there (a test checks it).

The file format is checked by the app (`NastyCatalog` in StepTellerCore): formato, versione, segnaposti, lunghezze,
livelli, situazioni, ore, eventi. A test checks that the files say the same thing.

Usage:
  python3 scripts/battute.py           writes the two outputs
  python3 scripts/battute.py --check   exit 1 if the outputs are not what the source gives
Standard library only. Change EDIZIONE (date of the change, AAAA-MM-GG) every time the catalog changes: the app
replaces its catalog only with an edition equal or newer.
"""
import json
import sys
from pathlib import Path

IOS = Path(__file__).resolve().parent.parent
ROOT = IOS.parent
CATALOG = IOS / 'docs/design/T-021-nasty/catalogo'
RULES = CATALOG / 'vincoli.json'
SWIFT = IOS / 'Sources/StepTellerCore/NastyCatalog+Bordo.swift'
SITE = ROOT / 'neat/nasty'

FORMATO = 'neat-battute'
VERSIONE = 1
EDIZIONE = '2026-11-19'
# Languages of the app: a catalog file for another code is an error.
LANGUAGES = ['it', 'en', 'de', 'fr', 'es', 'pt-BR', 'ja', 'ko', 'zh-Hans', 'zh-Hant']


def sources():
    """Approved catalog per language: `catalogo-approvato.json` is Italian, `lingue/<lingua>.json` the others."""
    out = {}
    paths = [CATALOG / 'catalogo-approvato.json'] + sorted((CATALOG / 'lingue').glob('*.json'))
    for path in paths:
        code = 'it' if path.parent == CATALOG else path.stem
        if code not in LANGUAGES:
            raise SystemExit(f'{path.name}: lingua sconosciuta «{code}» (ammesse: {", ".join(LANGUAGES)})')
        out[code] = json.loads(path.read_text(encoding='utf-8'))
    if 'it' not in out:
        raise SystemExit('Manca il catalogo italiano')
    return out


def catalog(code, approved, ore, evento):
    lines = []
    for a in approved:
        line = {'id': a['id'], 'livello': a['livello'], 'situazione': a['situazione']}
        text = a['testo']
        if ' / ' in text:
            title, text = text.split(' / ', 1)
            line['titolo'] = title
        line['testo'] = text
        if a['id'] in ore:
            line['ore'] = ore[a['id']]
        if a['id'] in evento:
            line['evento'] = evento[a['id']]
        lines.append(line)
    data = {'formato': FORMATO, 'versione': VERSIONE, 'edizione': EDIZIONE, 'lingua': code, 'battute': lines}
    return json.dumps(data, ensure_ascii=False, indent=1) + '\n'


def build():
    """{path: text} of every output."""
    rules = json.loads(RULES.read_text(encoding='utf-8'))
    ore, evento = rules['ore'], rules['evento']
    langs = sources()
    ids = {a['id'] for a in langs['it']}
    unknown = sorted((set(ore) | set(evento)) - ids)
    if unknown:
        raise SystemExit(f'Id in vincoli.json ma non nel catalogo italiano: {", ".join(unknown)}')
    files = {}
    swift = ['// Generated by scripts/battute.py from docs/design/T-021-nasty/catalogo/ (approved catalogs and vincoli.json):',
             '// do not edit by hand. Same text as neat/nasty/<lingua>/battute.json on the site (checked by a test).', '',
             'extension NastyLibrary {', '    /// The approved catalogs the app ships with, by language (works without network).',
             '    static let onBoardJSON: [String: String] = [']
    for code in sorted(langs, key=LANGUAGES.index):
        text = catalog(code, langs[code], ore, evento)
        if '"""#' in text:
            raise SystemExit(f'Il catalogo {code} contiene «"""#»: non entra in una stringa Swift')
        files[SITE / code / 'battute.json'] = text
        swift += [f'        "{code}": #"""', text + '"""#,']
    swift += ['    ]', '}', '']
    files[SWIFT] = '\n'.join(swift)
    return files


def main():
    files = build()
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items()
                 if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            raise SystemExit('Da rigenerare con scripts/battute.py: ' + ', '.join(stale))
        print('Catalogo allineato.')
        return
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        print('Scritto', path.relative_to(ROOT))


if __name__ == '__main__':
    main()
